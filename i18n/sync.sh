#!/bin/sh
# Copies the English dictionary into the apps and the web page. Run after editing strings.json.
set -e
cd "$(dirname "$0")/.."
mkdir -p android/brushcore/src/main/resources/i18n
cp i18n/strings.json android/brushcore/src/main/resources/i18n/en.json
cp i18n/strings.json ios/BrushCore/Sources/BrushCore/Resources/en.json
python3 - <<'PY'
import json
d = json.load(open('i18n/web.json', encoding='utf-8'))
open('web/public/i18n.js', 'w', encoding='utf-8').write('/* Generated by i18n/sync.sh from i18n/web.json */\nwindow.FOGMOSAS_EN = ' + json.dumps(d, ensure_ascii=False, indent=1) + ';\n')
PY
python3 i18n/extract.py
echo "synced"
